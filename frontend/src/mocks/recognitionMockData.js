import recognitionColumns from "constants/recognitionColumns";

const createRecognitionRow = (filename, values, ui = {}) => {
  const csvFields = recognitionColumns.reduce(
    (row, column) => ({
      ...row,
      [column]: column === "filename" ? filename : values[column] ?? "",
    }),
    {}
  );

  return {
    ...csvFields,
    confidence: ui.confidence,
    status: ui.status,
    issueTypes: ui.issueTypes ?? [],
    recommendation: ui.recommendation ?? "",
    detectionSource: ui.detectionSource ?? "QR+OCR",
    shelfZone: ui.shelfZone ?? "",
    category: ui.category ?? "",
    duplicateMerged: ui.duplicateMerged ?? false,
  };
};

